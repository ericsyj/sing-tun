//go:build linux

package tun

import (
	"slices"

	"github.com/sagernet/netlink"

	"golang.org/x/sys/unix"
)

// Kept separate from Android service setup so rule selection can be tested
// without a VpnService or privileged netlink access.

func (r *autoRedirect) androidVPNServiceRulePriority() int {
	if r.tunOptions.IPRoute2RuleIndex != 0 {
		return r.tunOptions.IPRoute2RuleIndex
	}
	return DefaultIPRoute2RuleIndex
}

// The kernel appends a rule after the existing rules of its priority and a
// default network table matches every destination, so a local network that
// appears after the default network needs a preceding priority to be reached.
func (r *autoRedirect) androidVPNServiceLocalRulePriority() int {
	return r.androidVPNServiceRulePriority() - 1
}

func (r *autoRedirect) androidVPNServiceRulePriorities() []int {
	return []int{r.androidVPNServiceLocalRulePriority(), r.androidVPNServiceRulePriority()}
}

type androidVPNServiceTables struct {
	physical      []int
	localNetworks []int
}

// netd adds one default network rule per interface of the default network
// (with 464xlat: the base interface and the clat interface, only the latter
// holding the IPv4 default route), so every table is kept in dump order and
// the kernel falls through on a lookup miss. The rule matching the VPN as the
// incoming interface only reaches the shared local network table, while a
// local physical network such as a tethering downstream keeps its routes in
// its own table with its own rule at the local network priority. The legacy
// system and legacy network rules share that select mask at other priorities
// and stay empty.
func discoverAndroidVPNServiceTables(ruleList []netlink.Rule, tunInterfaceName string) androidVPNServiceTables {
	var (
		tables          androidVPNServiceTables
		vpnLocalNetwork int
	)
	for _, rule := range ruleList {
		if rule.Table <= 0 || rule.Mark != 0 || rule.UIDRange != nil {
			continue
		}
		switch {
		case rule.Mask == androidNetIDMask:
			if !slices.Contains(tables.physical, rule.Table) {
				tables.physical = append(tables.physical, rule.Table)
			}
		case rule.IifName == tunInterfaceName && rule.OifName == "":
			if vpnLocalNetwork == 0 {
				vpnLocalNetwork = rule.Table
			}
		case rule.Priority == androidLocalNetworkRulePriority && rule.Mask == androidExplicitSelectMask && rule.IifName == "" && rule.OifName == "":
			if !slices.Contains(tables.localNetworks, rule.Table) {
				tables.localNetworks = append(tables.localNetworks, rule.Table)
			}
		}
	}
	if vpnLocalNetwork > 0 && !slices.Contains(tables.localNetworks, vpnLocalNetwork) {
		tables.localNetworks = append(tables.localNetworks, vpnLocalNetwork)
	}
	return tables
}

func (r *autoRedirect) androidVPNServiceFamilyRules(family int, vpnTable int, tables androidVPNServiceTables) []*netlink.Rule {
	priority := r.androidVPNServiceRulePriority()
	newRule := func(priority int, mark uint32, inputInterface string, table int) *netlink.Rule {
		rule := netlink.NewRule()
		rule.Priority = priority
		rule.Family = family
		rule.Mark = mark
		rule.MarkSet = true
		rule.Mask = int(r.effectiveMarkMask())
		rule.IifName = inputInterface
		rule.Table = table
		return rule
	}
	rules := []*netlink.Rule{newRule(priority, r.tunOptions.AutoRedirectInputMark, "", vpnTable)}
	// A reset generated by the REJECT chain keeps the reset mark of the
	// packet that triggered it and has to reach the client on the served
	// network instead of the netd VPN rule that catches unmarked flows.
	for _, table := range tables.localNetworks {
		rules = append(rules, newRule(priority, r.tunOptions.AutoRedirectResetMark, "", table))
	}
	// Bypassed local flows carry the tun address as their source and
	// Android ships no ip6tables nat table to rewrite it.
	if family == unix.AF_INET6 {
		return rules
	}
	for _, table := range tables.localNetworks {
		rules = append(rules, newRule(r.androidVPNServiceLocalRulePriority(), r.tunOptions.AutoRedirectOutputMark, "lo", table))
	}
	for _, table := range tables.physical {
		rules = append(rules, newRule(priority, r.tunOptions.AutoRedirectOutputMark, "lo", table))
	}
	return rules
}
